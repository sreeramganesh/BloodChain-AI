/**
 * On-demand generator for realistic inter-hospital transfers in a district
 */
export function getSyntheticTransfersForDistrict(state, district) {
  const hospitals = getHospitalsForDistrict(state, district);
  if (!hospitals || hospitals.length === 0) return [];

  const statuses = ["Completed", "Pending", "Approved", "In Transit", "Pending"];
  const reasons = [
    "Emergency cardiovascular surgery - immediate supply required.",
    "Trauma center critical reserve replenishment.",
    "Pediatric intensive care urgent transfusion.",
    "Oncology surgery cross-match allocation.",
    "Rare blood group emergency requirement.",
  ];

  const transfers = [];
  const count = Math.min(5, hospitals.length - 1);

  for (let i = 0; i < count; i++) {
    const fromHosp = hospitals[i];
    const toHosp = hospitals[(i + 1) % hospitals.length];
    const bg = BLOOD_GROUPS[(i * 2 + 1) % BLOOD_GROUPS.length];
    const units = [4, 15, 10, 8, 12][i % 5];
    const status = statuses[i % statuses.length];
    const code = (district || "").slice(0, 3).toUpperCase();

    transfers.push({
      id: `TRF-${code}-${101 + i * 23}`,
      blood: bg,
      blood_group: bg,
      units: units,
      from: fromHosp,
      from_location: fromHosp,
      to: toHosp,
      to_location: toHosp,
      date: `Today, 0${9 + i}:30 AM`,
      status: status,
      reason: reasons[i % reasons.length],
      requested_by: `Dr. Medical Officer (${fromHosp})`,
      district: district,
      data_type: "Synthetic/Demo",
    });
  }

  return transfers;
}

